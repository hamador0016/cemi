//! `cemi types`: TypeScript declarations or a zod schema for the variables
//! of a project's cemi.toml. Only cemi.toml is read, never a vault, so the
//! output is the same on every computer and in CI.

use crate::project::{ProjectFile, RefSpec};

#[derive(Clone, Copy, Debug, PartialEq, Eq, clap::ValueEnum)]
pub enum Format {
    /// Declarations for process.env (NodeJS.ProcessEnv)
    Ts,
    /// A zod schema that checks process.env when the app starts
    Zod,
}

const HEADER: &str = "// Generated by `cemi types` from cemi.toml. Do not edit: run it again after changing cemi.toml.\n";

struct Var<'a> {
    name: &'a str,
    spec: &'a RefSpec,
    file: bool,
}

fn vars(p: &ProjectFile) -> Vec<Var<'_>> {
    let mut out: Vec<Var> = p
        .env
        .iter()
        .map(|(name, spec)| Var {
            name,
            spec,
            file: false,
        })
        .chain(p.files.iter().map(|(name, spec)| Var {
            name,
            spec,
            file: true,
        }))
        .collect();
    out.sort_by(|a, b| a.name.cmp(b.name));
    out
}

/// A JSDoc comment: the purpose from cemi.toml, and where the value comes from.
fn doc(v: &Var, indent: &str) -> String {
    let mut text = String::new();
    if let Some(p) = v.spec.purpose() {
        text.push_str(p.trim());
        text.push_str(". ");
    }
    if v.file {
        text.push_str("Path to a file with ");
    } else {
        text.push_str("From ");
    }
    text.push_str(v.spec.text());
    // Nothing in the text may close the comment.
    let text = text.replace("*/", "* /");
    format!("{indent}/** {text} */\n")
}

pub fn generate(p: &ProjectFile, format: Format) -> String {
    let vars = vars(p);
    let mut s = String::from(HEADER);
    match format {
        Format::Ts => {
            s.push_str("declare global {\n  namespace NodeJS {\n    interface ProcessEnv {\n");
            for v in &vars {
                s.push_str(&doc(v, "      "));
                s.push_str(&format!("      {}: string;\n", v.name));
            }
            s.push_str("    }\n  }\n}\n\nexport {};\n");
        }
        Format::Zod => {
            s.push_str("import { z } from \"zod\";\n\nexport const envSchema = z.object({\n");
            for v in &vars {
                s.push_str(&doc(v, "  "));
                s.push_str(&format!("  {}: z.string().min(1),\n", v.name));
            }
            s.push_str(concat!(
                "});\n\n",
                "export type Env = z.infer<typeof envSchema>;\n\n",
                "/** Fails at startup, naming each missing variable, instead of later in a request. */\n",
                "export const env: Env = envSchema.parse(process.env);\n",
            ));
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn project() -> ProjectFile {
        toml::from_str(
            r#"
            [env]
            STRIPE_SECRET_KEY = { ref = "stripe#secret", purpose = "payments */ careful" }
            DATABASE_URL = "db#url"
            [files]
            GOOGLE_APPLICATION_CREDENTIALS = "gcp#key"
            "#,
        )
        .unwrap()
    }

    #[test]
    fn typescript_declarations() {
        let out = generate(&project(), Format::Ts);
        assert!(out.contains("interface ProcessEnv {"));
        assert!(out.contains("      /** From db#url */\n      DATABASE_URL: string;"));
        assert!(out.contains("/** payments * / careful. From stripe#secret */"));
        assert!(out.contains("/** Path to a file with gcp#key */"));
        // Sorted by name.
        let a = out.find("DATABASE_URL:").unwrap();
        let b = out.find("GOOGLE_APPLICATION_CREDENTIALS:").unwrap();
        let c = out.find("STRIPE_SECRET_KEY:").unwrap();
        assert!(a < b && b < c);
    }

    #[test]
    fn zod_schema() {
        let out = generate(&project(), Format::Zod);
        assert!(out.contains("import { z } from \"zod\";"));
        assert!(out.contains("  DATABASE_URL: z.string().min(1),"));
        assert!(out.contains("export const env: Env = envSchema.parse(process.env);"));
    }
}
